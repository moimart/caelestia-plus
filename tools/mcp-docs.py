#!/usr/bin/env python3
"""Writes docs/mcp/TOOLS.md from the MCP server's own tool definitions, so the
reference never drifts from the code.

    python3 tools/mcp-docs.py
"""

import importlib.util
import pathlib

repo = pathlib.Path(__file__).resolve().parent.parent
server = repo / "shell/mcp/caelestia_mcp.py"
out = repo / "docs/mcp/TOOLS.md"

spec = importlib.util.spec_from_file_location("caelestia_mcp", server)
mcp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mcp)

# The areas, in the order the README presents them
areas = [
    ("See the desktop", ["screenshot", "list_monitors", "list_windows"]),
    ("Lock", ["lock_status", "lock", "unlock"]),
    ("Wallpaper", ["wallpaper_list", "wallpaper_get", "wallpaper_set", "wallpaper_clear_monitor"]),
    ("Colours", ["scheme_get", "scheme_list", "scheme_set"]),
    ("Settings", ["config_get", "config_set"]),
    ("Desktop", ["media_status", "media_control", "brightness", "toast", "notifications", "toggle", "panel"]),
    ("Shortcuts", ["keybinds"]),
    ("Emoji", ["emoji"]),
    ("Window cards", ["cards"]),
    ("Desktop widgets", ["widgets"]),
    ("Camera", ["camera"]),
    ("Anything else", ["ipc_list", "ipc_call"]),
]
listed = {name for _, names in areas for name in names}
missing = sorted(set(mcp.TOOLS) - listed)
if missing:
    areas.append(("Other", missing))


def param_type(p):
    if "enum" in p:
        return " \\| ".join(f"`{v}`" for v in p["enum"])
    t = p.get("type")
    if not t:
        return "any"
    return f"`{t}`" if isinstance(t, str) else " \\| ".join(f"`{x}`" for x in t)


lines = [
    "# MCP tools",
    "",
    "<!-- Generated by tools/mcp-docs.py from shell/mcp/caelestia_mcp.py; don't edit by hand. -->",
    "",
    f"The caelestia MCP server has {len(mcp.TOOLS)} tools. What they're for, and how to",
    "set it up: [README.md](README.md).",
    "",
]
for area, names in areas:
    lines.append(f"- **{area}**: " + ", ".join(f"[`{n}`](#{n})" for n in names))
lines.append("")

for area, names in areas:
    lines += [f"## {area}", ""]
    for name in names:
        s = mcp.TOOLS[name]["spec"]
        schema = s["inputSchema"]
        lines += [f"### `{name}`", "", s["description"], ""]
        props = schema.get("properties", {})
        if props:
            required = set(schema.get("required", []))
            lines += ["| Parameter | Type | Required | Description |", "| --- | --- | --- | --- |"]
            for pname, p in props.items():
                desc = p.get("description", "").replace("|", "\\|")
                lines.append(f"| `{pname}` | {param_type(p)} | {'yes' if pname in required else ''} | {desc} |")
            lines.append("")
        else:
            lines += ["No parameters.", ""]

out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines).rstrip() + "\n")
print(f"Wrote {out.relative_to(repo)}: {len(mcp.TOOLS)} tools")
